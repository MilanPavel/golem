def export_swift_methods(directory: Path) -> Path:
    """Write ``MethodAccess.swift``, the Swift counterpart of ``browser-methods.ts``.

    The app may call only the methods in ``MethodAccess.device``.
    """
    directory.mkdir(parents=True, exist_ok=True)

    def set_literal(*levels: str) -> str:
        names = _method_names(*levels)
        return "[\n" + "".join(f'        "{name}",\n' for name in names) + "    ]"

    path = directory / "MethodAccess.swift"
    path.write_text(
        SWIFT_BANNER
        + "\n"
        + "public enum MethodAccess {\n"
        + f"    public static let device: Set<String> = {set_literal('device')}\n"
        + "\n"
        + f"    public static let browser: Set<String> = {set_literal('browser', 'device')}\n"
        + "\n"
        + f"    public static let localOnly: Set<String> = {set_literal('local')}\n"
        + "}\n",
        encoding="utf-8",
    )
    return path


